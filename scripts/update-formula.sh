#!/usr/bin/env bash
# Render Formula/mtf-facts.rb for a release of modulestf/facts.
#
# Usage: scripts/update-formula.sh [tag]
#
# With no tag it takes the latest release that is not a pre-release. It reads
# the release's SHA256SUMS and, unless SKIP_ATTESTATION=1, checks the build
# provenance of every binary with `gh attestation verify` first, so the formula
# never pins a binary the facts release workflow did not build.
set -euo pipefail

repo=modulestf/facts
tag=${1:-$(gh api "repos/${repo}/releases/latest" --jq .tag_name)}
if ! [[ $tag =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
	echo "update-formula: ${tag} is not a release version vMAJOR.MINOR.PATCH" >&2
	exit 2
fi
base="https://github.com/${repo}/releases/download/${tag}"

tmp=$(mktemp -d "${TMPDIR:-/tmp}/update-formula.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
curl -fsSL --proto '=https' --tlsv1.2 --retry 2 --max-time 60 -o "${tmp}/SHA256SUMS" "${base}/SHA256SUMS"

sum() {
	local name="mtf-facts_${tag}_$1" s
	s=$(awk -v n="$name" '$2 == n { print $1 }' "${tmp}/SHA256SUMS")
	if ! [[ $s =~ ^[0-9a-f]{64}$ ]]; then
		echo "update-formula: ${name} is not in SHA256SUMS of ${tag}" >&2
		exit 1
	fi
	if [ "${SKIP_ATTESTATION:-0}" != 1 ]; then
		curl -fsSL --proto '=https' --tlsv1.2 --retry 2 --max-time 120 -o "${tmp}/${name}" "${base}/${name}"
		(cd "$tmp" && echo "${s}  ${name}" | shasum -a 256 -c - > /dev/null)
		gh attestation verify "${tmp}/${name}" -R "$repo" \
			--signer-workflow "${repo}/.github/workflows/release.yml" \
			--source-ref "refs/tags/${tag}" --deny-self-hosted-runners > /dev/null
	fi
	echo "$s"
}

darwin_arm64=$(sum darwin_arm64)
darwin_amd64=$(sum darwin_amd64)
linux_arm64=$(sum linux_arm64)
linux_amd64=$(sum linux_amd64)

cat > Formula/mtf-facts.rb <<RUBY
# Generated by scripts/update-formula.sh from the ${tag} release of ${repo}.
class MtfFacts < Formula
  desc "Offline facts about Terraform module trees, for modulestf reviews"
  homepage "https://github.com/${repo}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${base}/mtf-facts_${tag}_darwin_arm64"
      sha256 "${darwin_arm64}"
    end
    on_intel do
      url "${base}/mtf-facts_${tag}_darwin_amd64"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/mtf-facts_${tag}_linux_arm64"
      sha256 "${linux_arm64}"
    end
    on_intel do
      url "${base}/mtf-facts_${tag}_linux_amd64"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install Dir["mtf-facts_*"].first => "mtf-facts"
    chmod 0755, bin/"mtf-facts"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/mtf-facts --version")
  end
end
RUBY
echo "Formula/mtf-facts.rb: ${tag}"
